"""Private, immutable evidence upload core for co-tenant identity documents."""
from contextlib import contextmanager
from io import BytesIO
from pathlib import PurePath

from PIL import Image, UnidentifiedImageError
from django.core.exceptions import PermissionDenied, ValidationError
from django.db import IntegrityError, transaction

from core.booking_identifiers import normalize_companion_cccd
from core.dich_vu.yeu_cau_nguoi_o_cung import _require_active_request_contract
from core.models import ChungTuDanhTinhNguoiOCung, DanhTinhNguoiOCung, YeuCauNguoiOCung


MAX_EVIDENCE_SIZE = 5 * 1024 * 1024
ALLOWED_FORMATS = {
    "JPEG": ("image/jpeg", ".jpg"),
    "PNG": ("image/png", ".png"),
    "WEBP": ("image/webp", ".webp"),
}
PENDING_STATES = ("cho_xac_minh", "cho_bo_sung")


@contextmanager
def atomic_identity_evidence_submission():
    """Rollback DB and delete only files first created in this submission."""
    created = []
    try:
        with transaction.atomic():
            yield created
    except Exception:
        for evidence in created:
            if evidence.tep and evidence.tep.name:
                evidence.tep.storage.delete(evidence.tep.name)
        raise


def validate_identity_image(uploaded):
    if not uploaded:
        raise ValidationError("Vui long chon anh chung tu danh tinh.")
    if uploaded.size > MAX_EVIDENCE_SIZE:
        raise ValidationError("Anh chung tu danh tinh khong duoc vuot qua 5 MB.")
    try:
        payload = uploaded.read()
        with Image.open(BytesIO(payload)) as image:
            image.verify()
            image_format = image.format
    except (UnidentifiedImageError, OSError, ValueError):
        raise ValidationError("Tep tai len khong phai anh JPEG, PNG hoac WEBP hop le.")
    finally:
        uploaded.seek(0)
    if image_format not in ALLOWED_FORMATS:
        raise ValidationError("Chi chap nhan anh JPEG, PNG hoac WEBP.")
    mime_type, suffix = ALLOWED_FORMATS[image_format]
    raw_name = str(getattr(uploaded, "name", "") or "")
    original_name = raw_name.replace("\\", "/").rsplit("/", 1)[-1][:255] or f"evidence{suffix}"
    supplied_suffix = PurePath(original_name).suffix.lower()
    if supplied_suffix == ".jpeg":
        supplied_suffix = ".jpg"
    if supplied_suffix not in {".jpg", ".png", ".webp"} or supplied_suffix != suffix:
        raise ValidationError("Phan mo rong tep khong khop noi dung anh da kiem tra.")
    # The storage filename is generated by upload_to; this name only supplies
    # the verified suffix and cannot carry a client path.
    uploaded.name = f"evidence{suffix}"
    return mime_type, original_name, uploaded.size


def _resolve_locked_identity(cccd):
    try:
        return DanhTinhNguoiOCung.objects.select_for_update().get(cccd=cccd)
    except DanhTinhNguoiOCung.DoesNotExist:
        try:
            with transaction.atomic():
                return DanhTinhNguoiOCung.objects.create(cccd=cccd)
        except IntegrityError:
            return DanhTinhNguoiOCung.objects.select_for_update().get(cccd=cccd)


def _locked_request_for_upload(request_id):
    return YeuCauNguoiOCung.objects.select_for_update().select_related(
        "hop_dong__dat_phong__nguoi_thue", "nguoi_yeu_cau"
    ).get(pk=request_id)


def upload_identity_evidence(*, request_id, actor, idempotency_key, uploaded):
    """Create a new immutable identity-evidence version for one pending request."""
    if not idempotency_key or len(idempotency_key) > 64:
        raise ValidationError("Idempotency key khong hop le.")
    with atomic_identity_evidence_submission() as created:
        request = _locked_request_for_upload(request_id)
        if request.nguoi_yeu_cau.tai_khoan_id != getattr(actor, "id", None):
            raise PermissionDenied("Khong co quyen tai chung tu cho request nay.")
        if request.trang_thai not in PENDING_STATES:
            raise ValidationError("Chi request dang cho xu ly moi nhan chung tu danh tinh.")
        _require_active_request_contract(request)
        cccd = normalize_companion_cccd(request.cccd)
        if not cccd:
            raise ValidationError("CCCD hop le la bat buoc.")
        identity = _resolve_locked_identity(cccd)
        existing = ChungTuDanhTinhNguoiOCung.objects.filter(
            danh_tinh=identity, nguoi_tai_len=actor, ma_idempotency=idempotency_key
        ).first()
        if existing:
            if existing.yeu_cau_nguon_id != request.pk:
                raise ValidationError("Idempotency key da thuoc chung tu khac.")
            return existing, False
        mime_type, original_name, size = validate_identity_image(uploaded)
        next_version = (
            ChungTuDanhTinhNguoiOCung.objects.select_for_update()
            .filter(danh_tinh=identity).order_by("-so_phien_ban").values_list("so_phien_ban", flat=True).first()
            or 0
        ) + 1
        evidence = ChungTuDanhTinhNguoiOCung(
            danh_tinh=identity, yeu_cau_nguon=request, nguoi_tai_len=actor,
            so_phien_ban=next_version, ma_idempotency=idempotency_key,
            tep=uploaded, ten_tap_tin_goc=original_name, mime_type=mime_type,
            kich_thuoc=size,
        )
        try:
            evidence.save(force_insert=True)
        except Exception:
            if evidence.tep and evidence.tep.name:
                evidence.tep.storage.delete(evidence.tep.name)
            raise
        created.append(evidence)
        return evidence, True
